#!/usr/bin/env bash
# WireGuard VPN server, driven by vpn.json in the same folder. Run as root on Ubuntu with ufw.
#
#   bash vpn.sh setup            install or update WireGuard from vpn.json (safe to re-run)
#   bash vpn.sh sync             make the people on the server match "peers" in vpn.json
#   bash vpn.sh add <name>       add a person (also adds them to vpn.json)
#   bash vpn.sh remove <name>    remove a person (also from vpn.json); works immediately
#   bash vpn.sh list             everyone on the VPN: address, last seen, data used
#   bash vpn.sh uninstall        undo setup (old config kept in /root/backups/)
#
# Each new person gets /etc/wireguard/clients/<name>.conf. It contains their private key:
# copy it to them privately, then delete it from the server.
#
# Server state lives in /etc/wireguard: server.key/.pub, peers/<name> ("<public key> <ip>"),
# and wg0.conf, which is regenerated from vpn.json + peers/ every time.
set -euo pipefail

dir=$(cd "$(dirname "$0")" && pwd)
json=$dir/vpn.json
WG=/etc/wireguard
IF=wg0

die() { echo "$*" >&2; exit 1; }
[[ $EUID -eq 0 ]] || die "Run as root."

# --- settings ------------------------------------------------------------------
load() {
  command -v jq >/dev/null || die "jq is missing. Run: bash vpn.sh setup"
  [[ -f $json ]] || die "No vpn.json next to vpn.sh."
  pub_if=$(ip -4 route show default | awk '{print $5; exit}')
  host=$(jq -r '.server.host // "auto"' "$json")
  if [[ $host == auto ]]; then
    host=$(ip -4 -o addr show dev "$pub_if" scope global | awk '{print $4}' | cut -d/ -f1 | head -1)
  fi
  port=$(jq -r '.server.port // 51820' "$json")
  subnet=$(jq -r '.server.subnet // "10.8.0.0/24"' "$json")
  dns=$(jq -r '(.server.dns // ["1.1.1.1", "1.0.0.1"]) | join(", ")' "$json")
  [[ -n $pub_if && -n $host ]] || die "Could not find the public interface and IP."
  [[ $port =~ ^[0-9]+$ ]] || die "server.port in vpn.json must be a number."
  [[ $subnet =~ ^([0-9]+\.[0-9]+\.[0-9]+)\.0/24$ ]] || die "server.subnet in vpn.json must look like 10.8.0.0/24."
  prefix=${BASH_REMATCH[1]}
}

valid_name() { [[ $1 =~ ^[a-z0-9][a-z0-9-]{0,30}$ ]] || die "Bad name '$1': use lowercase letters, digits and dashes."; }

json_peers() { jq -r '(.peers // [])[]' "$json"; }

json_edit() {   # json_edit <jq filter> <name>
  jq --arg n "$2" "$1" "$json" >"$json.tmp" && mv "$json.tmp" "$json"
}

# --- peers ---------------------------------------------------------------------
new_peer() {
  local name=$1 used octet= i priv pub
  valid_name "$name"
  [[ ! -e $WG/peers/$name ]] || die "There is already a peer called '$name'."
  used=$(cat "$WG"/peers/* 2>/dev/null | awk '{print $2}' | awk -F. '{print $4}' || true)
  for i in $(seq 2 254); do
    if ! grep -qx "$i" <<<"$used"; then octet=$i; break; fi
  done
  [[ -n $octet ]] || die "No free VPN addresses left."

  umask 077
  priv=$(wg genkey)
  pub=$(wg pubkey <<<"$priv")
  echo "$pub $prefix.$octet" >"$WG/peers/$name"

  # ::/0 keeps IPv6 inside the tunnel so it can't leak around it.
  cat >"$WG/clients/$name.conf" <<EOF
[Interface]
PrivateKey = $priv
Address = $prefix.$octet/32
DNS = $dns

[Peer]
PublicKey = $(cat "$WG/server.pub")
Endpoint = $host:$port
AllowedIPs = 0.0.0.0/0, ::/0
PersistentKeepalive = 25
EOF
  echo "Added '$name' ($prefix.$octet). Config: $WG/clients/$name.conf  (copy it to them, then delete it)"
}

drop_peer() {
  rm -f "$WG/peers/$1" "$WG/clients/$1.conf"
  echo "Removed '$1'."
}

sync_peers() {   # add people listed in vpn.json, remove people who aren't
  local name f wanted
  wanted=$(json_peers)
  while IFS= read -r name; do
    if [[ -n $name && ! -e $WG/peers/$name ]]; then new_peer "$name"; fi
  done <<<"$wanted"
  for f in "$WG"/peers/*; do
    [[ -e $f ]] || continue
    if ! grep -qxF "${f##*/}" <<<"$wanted"; then drop_peer "${f##*/}"; fi
  done
}

# --- wg0.conf ------------------------------------------------------------------
write_conf() {
  local f pub ip
  umask 077
  {
    echo "# Generated by vpn.sh from vpn.json and $WG/peers/. Edit those, not this file."
    echo "[Interface]"
    echo "Address = $prefix.1/24"
    echo "ListenPort = $port"
    echo "PrivateKey = $(cat "$WG/server.key")"
    echo "PostUp = iptables -t nat -A POSTROUTING -s $subnet -o $pub_if -j MASQUERADE"
    echo "PostUp = iptables -t mangle -A FORWARD -o %i -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu"
    echo "PostDown = iptables -t nat -D POSTROUTING -s $subnet -o $pub_if -j MASQUERADE"
    echo "PostDown = iptables -t mangle -D FORWARD -o %i -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu"
    for f in "$WG"/peers/*; do
      [[ -e $f ]] || continue
      read -r pub ip <"$f"
      [[ $ip == "$prefix".* ]] || die "Peer ${f##*/} has address $ip outside $subnet. Don't change the subnet after setup."
      printf '\n# name: %s\n[Peer]\nPublicKey = %s\nAllowedIPs = %s/32\n' "${f##*/}" "$pub" "$ip"
    done
  } >"$WG/$IF.conf.new"
  mv "$WG/$IF.conf.new" "$WG/$IF.conf"
}

apply() {   # live update; restart only when asked (setup)
  if ! systemctl is-active -q "wg-quick@$IF"; then
    systemctl start "wg-quick@$IF"
  elif [[ ${1:-} == restart ]]; then
    systemctl restart "wg-quick@$IF"
  else
    wg syncconf "$IF" <(wg-quick strip "$IF")
  fi
}

# --- commands ------------------------------------------------------------------
cmd_setup() {
  # Checks first: nothing is changed if one fails. (grep >/dev/null, not -q, because of pipefail.)
  ufw status | grep '^Status: active' >/dev/null || die "This script expects ufw to be active."
  iptables -S ufw-before-forward | grep 'RELATED,ESTABLISHED -j ACCEPT' >/dev/null \
    || die "ufw doesn't let replies to forwarded traffic back in."

  local backup old_port
  backup=/root/backups/wireguard-$(date +%Y%m%d-%H%M%S)
  mkdir -p "$backup"
  iptables-save >"$backup/iptables.rules"
  ip6tables-save >"$backup/ip6tables.rules"
  cp /etc/ufw/user.rules /etc/ufw/user6.rules "$backup/"
  [[ -d $WG ]] && cp -a "$WG" "$backup/wireguard"
  echo "Backup saved in $backup"

  if ! command -v wg >/dev/null || ! command -v jq >/dev/null || ! command -v qrencode >/dev/null; then
    apt-get update -q -o DPkg::Lock::Timeout=300
    apt-get install -y -q --no-install-recommends -o DPkg::Lock::Timeout=300 wireguard-tools jq qrencode
  fi
  load
  echo "Server: $host:$port on $pub_if, VPN subnet $subnet"
  if ! ip link show "$IF" >/dev/null 2>&1 && ss -Hlun "sport = :$port" | grep . >/dev/null; then
    die "UDP port $port is already in use."
  fi

  install -d -m 700 "$WG" "$WG/clients" "$WG/peers"
  umask 077
  if [[ ! -f $WG/server.key ]]; then
    wg genkey >"$WG/server.key"
    wg pubkey <"$WG/server.key" >"$WG/server.pub"
  fi

  # Older install (separate scripts): import its peers, remove its commands.
  if [[ -f $WG/$IF.conf ]] && [[ -z $(ls -A "$WG/peers") ]]; then
    awk '/^# name: /{n = substr($0, 9)} /^PublicKey/ && n {pk = $3} /^AllowedIPs/ && n {split($3, a, "/"); print n, pk, a[1]; n = ""}' \
      "$WG/$IF.conf" | while read -r n pk ip; do echo "$pk $ip" >"$WG/peers/$n"; echo "Kept existing peer '$n' ($ip)"; done
  fi
  rm -f "$WG/vpn.env" /usr/local/sbin/vpn-add-peer /usr/local/sbin/vpn-remove-peer /usr/local/sbin/vpn-list-peers

  old_port=$(awk -F' *= *' '/^ListenPort/ {print $2}' "$WG/$IF.conf" 2>/dev/null || true)
  if [[ -n $old_port && $old_port != "$port" ]]; then ufw delete allow "$old_port/udp" || true; fi

  sync_peers
  write_conf

  echo "net.ipv4.ip_forward = 1" >/etc/sysctl.d/99-wireguard.conf
  chmod 644 /etc/sysctl.d/99-wireguard.conf
  sysctl -q -p /etc/sysctl.d/99-wireguard.conf

  ufw allow "$port/udp" comment 'WireGuard VPN'
  ufw route allow in on "$IF" out on "$pub_if" comment 'WireGuard VPN to internet'

  systemctl enable -q "wg-quick@$IF"
  apply restart

  echo
  wg show "$IF" | head -4
  echo "IPv4 forwarding: $(sysctl -n net.ipv4.ip_forward)"
  ufw status | grep -E "$port/udp|$IF" || true
  echo
  cmd_list
}

cmd_sync() { load; sync_peers; write_conf; apply; cmd_list; }

cmd_add() {
  [[ -n ${1:-} ]] || die "Usage: bash vpn.sh add <name>"
  load; new_peer "$1"
  json_edit '.peers = ((.peers // []) | if any(.[]; . == $n) then . else . + [$n] end)' "$1"
  write_conf; apply
  if [[ ${2:-} == --qr ]]; then qrencode -t ansiutf8 <"$WG/clients/$1.conf"; fi
}

cmd_remove() {
  [[ -n ${1:-} ]] || die "Usage: bash vpn.sh remove <name>"
  load
  [[ -e $WG/peers/$1 ]] || die "No peer called '$1'. See: bash vpn.sh list"
  drop_peer "$1"
  json_edit '.peers = ((.peers // []) | map(select(. != $n)))' "$1"
  write_conf; apply
}

cmd_list() {
  local f pub ip now handshake rx tx s seen
  declare -A names
  for f in "$WG"/peers/*; do
    [[ -e $f ]] || continue
    read -r pub ip <"$f"
    names[$pub]=${f##*/}
  done
  now=$(date +%s)
  printf '%-24s %-12s %-12s %11s %9s\n' NAME ADDRESS LAST-SEEN DOWNLOADED UPLOADED
  while IFS=$'\t' read -r pub _ _ ip handshake rx tx _; do
    s=$((now - handshake))
    if ((handshake == 0)); then seen=never
    elif ((s < 60)); then seen="${s}s ago"
    elif ((s < 3600)); then seen="$((s / 60))m ago"
    elif ((s < 86400)); then seen="$((s / 3600))h ago"
    else seen="$((s / 86400))d ago"; fi
    # Downloaded/uploaded are from the person's side.
    printf '%-24s %-12s %-12s %11s %9s\n' "${names[$pub]:-(unknown)}" "${ip%/32}" "$seen" \
      "$(numfmt --to=iec "$tx")" "$(numfmt --to=iec "$rx")"
  done < <(wg show "$IF" dump | tail -n +2)
}

cmd_uninstall() {
  local port dest
  port=$(awk -F' *= *' '/^ListenPort/ {print $2}' "$WG/$IF.conf")
  systemctl disable --now "wg-quick@$IF" || true
  ufw delete allow "$port/udp" || true
  ufw route delete allow in on "$IF" out on "$(ip -4 route show default | awk '{print $5; exit}')" || true
  rm -f /etc/sysctl.d/99-wireguard.conf
  sysctl -q -w net.ipv4.ip_forward=0
  dest=/root/backups/wireguard-removed-$(date +%Y%m%d-%H%M%S)
  mkdir -p /root/backups
  mv "$WG" "$dest"
  echo "VPN removed. Old config kept in $dest"
}

case ${1:-} in
  setup) cmd_setup ;;
  sync) cmd_sync ;;
  add) cmd_add "${2:-}" "${3:-}" ;;
  remove) cmd_remove "${2:-}" ;;
  list) cmd_list ;;
  uninstall) cmd_uninstall ;;
  *) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
